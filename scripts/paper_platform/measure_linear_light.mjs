import {chromium} from '../../apps/paper_workspace/collaboration/node_modules/playwright-core/index.mjs'
import {mkdirSync,writeFileSync} from 'node:fs'
const out=new URL('../../.omx/artifacts/linear-refresh/precision/',import.meta.url)
mkdirSync(out,{recursive:true})
const b=await chromium.launch()
const p=await b.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1,reducedMotion:'reduce'})
await p.addInitScript(()=>{localStorage.setItem('paper-workspace-theme','light');localStorage.setItem('collab-name','Test Author');localStorage.setItem('collab-name-user-set','1')})
await p.goto(`${process.env.PAPER_E2E_URL||'http://127.0.0.1:18440'}/p/light-reference-${Date.now()}?lang=en`)
await p.waitForFunction(()=>workspaceReadyForCompile)
await p.evaluate(()=>document.fonts.ready)
const data={}
async function sample(key,selector,property){data[key]=await p.locator(selector).first().evaluate((e,prop)=>getComputedStyle(e)[prop],property)}
await p.locator('.file').filter({hasText:'references.bib'}).click({button:'right'})
await sample('menu-surface','#tree-menu','backgroundColor')
await sample('menu-border','#tree-menu','borderTopColor')
await sample('menu-text','#tree-menu [data-action=rename]','color')
await p.keyboard.press('Home');await p.keyboard.press('ArrowDown')
await p.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
await sample('menu-selected','#tree-menu [data-action=rename]','backgroundColor')
await p.locator('#tree-menu').screenshot({path:new URL('light-menu.png',out).pathname})
await p.keyboard.press('Escape')
const editor=p.locator('#editor-view .cm-content')
await editor.click();await p.keyboard.press('Control+Home');await p.keyboard.press('Shift+End')
await p.waitForFunction(()=>!document.querySelector('#selection-toolbar').hidden)
await sample('toolbar-surface','#selection-toolbar','backgroundColor')
await sample('toolbar-border','#selection-toolbar','borderTopColor')
await sample('toolbar-icon','#selection-toolbar button svg','color')
await p.locator('#selection-toolbar').screenshot({path:new URL('light-selection-toolbar.png',out).pathname})
writeFileSync(new URL('light-rendered-metrics.json',out),JSON.stringify({viewport:{width:1600,height:1000,dpr:1},values:data},null,2))
await b.close()
console.log('7 light DOM samples saved')
