  await expect(tab).toHaveCSS('border-radius', '8px 8px 0px 0px')
  await expect(tab).toHaveCSS('border-top-width', '1px')
  await expect(tab).toHaveCSS('border-bottom-color', 'rgba(0, 0, 0, 0)')
  await expect(modes.locator('#open-rebuttal')).not.toHaveAttribute('aria-current')
  await expect(modes.locator('#open-rebuttal')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  const primary = page.locator('#ask')
  await expect(primary).toHaveCSS('transition-duration', '0s')
  await primary.hover()
  const hover = await primary.evaluate(e => getComputedStyle(e).backgroundColor)
  await page.mouse.down()
  const active = await primary.evaluate(e => getComputedStyle(e).backgroundColor)
  expect(active).not.toBe(hover)
  // Release outside the button so the pointer probe never sends an LLM request.
  await page.mouse.move(1599, 999)
  await page.mouse.up()
