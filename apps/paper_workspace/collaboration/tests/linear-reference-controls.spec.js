test('hovering quiet toolbar actions preserves their geometry and hit target', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/p/quiet-geometry-${Date.now()}?lang=en`)
  await page.waitForFunction(() => workspaceReadyForCompile)
  for (const selector of ['#new-file', '#toggle-sidebar', '#toggle-assistant', '.theme-trigger', '#editor-zoom-in', '#refresh-pdf', '#close-assistant']) {
    const button = page.locator(selector)
    const before = await button.boundingBox()
    await button.hover()
    const after = await button.boundingBox()
    expect(after.width, selector).toBe(before.width)
    expect(after.height, selector).toBe(before.height)
    const hit = await button.evaluate(el => {
      const r = el.getBoundingClientRect()
      return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) && getComputedStyle(el).maskImage === 'none'
    })
    expect(hit, selector).toBe(true)
  }
})

test('primary text keeps contrast through actual hover and pressed states', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/p/primary-contrast-${Date.now()}?lang=en`)
  await page.waitForFunction(() => workspaceReadyForCompile)
  const primary = page.locator('#ask')
  const ratio = () => primary.evaluate(e => {
    const canvas = document.createElement('canvas'); canvas.width = canvas.height = 1
    const ctx = canvas.getContext('2d', { willReadFrequently: true })
    const luminance = color => {
      ctx.fillStyle = color; ctx.fillRect(0, 0, 1, 1)
      const [r, g, b] = ctx.getImageData(0, 0, 1, 1).data
      return [r, g, b].map(x => x / 255).map(x => x <= .04045 ? x / 12.92 : ((x + .055) / 1.055) ** 2.4).reduce((sum, x, i) => sum + x * [.2126, .7152, .0722][i], 0)
    }
    const style = getComputedStyle(e), a = luminance(style.color), b = luminance(style.backgroundColor)
    return (Math.max(a, b) + .05) / (Math.min(a, b) + .05)
  })
  expect(await ratio()).toBeGreaterThanOrEqual(4.5)
  await primary.hover()
  expect(await ratio()).toBeGreaterThanOrEqual(4.5)
  await page.mouse.down()
  expect(await ratio()).toBeGreaterThanOrEqual(4.5)
  await page.mouse.move(1, 999)
  await page.mouse.up()
})

