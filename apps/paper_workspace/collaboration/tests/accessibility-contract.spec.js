import { expect, test } from './fixtures.js'

for (const theme of ['light', 'dark']) test(`assistant tabs expose named panels and one keyboard entry in ${theme}`, async ({ page }) => {
  let requests = 0
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.addInitScript(theme => localStorage.setItem('paper-workspace-theme', theme), theme)
  await page.route('**/api/codex', route => { requests++; return route.abort() })
  await page.goto(`/p/tab-contract-${theme}-${Date.now()}?lang=en`)
  await page.waitForFunction(() => workspaceReadyForCompile)
  const revise = page.getByRole('tab', { name: 'Revise', exact: true })
  await revise.focus()
  await page.keyboard.press('Tab')
  await expect(page.locator('#instruction')).toBeFocused()
  await revise.focus()
  for (const [key, name] of [['ArrowRight', 'Comments'], ['End', 'Tasks'], ['ArrowRight', 'Revise'], ['ArrowLeft', 'Tasks'], ['Home', 'Revise']]) {
    await page.keyboard.press(key)
    const selected = page.getByRole('tab', { name, exact: true })
    await expect(selected).toBeFocused()
    await expect(selected).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('tabpanel', { name, exact: true })).toBeVisible()
    await expect(page.getByRole('tab', { selected: true })).toHaveCount(1)
  }
  await page.locator('#workspace-language').selectOption('ko')
  await page.locator('[data-tab=comments]').click()
  await expect(page.getByRole('tabpanel', { name: '댓글', exact: true })).toBeVisible()
  expect(requests).toBe(0)
})

for (const surface of ['workspace', 'hub']) test(`${surface} profile and appearance dialogs retain their accessible names`, async ({ page }) => {
  await page.goto(surface === 'hub' ? '/hub.html?lang=en' : `/p/dialog-contract-${Date.now()}?lang=en`)
  const profileTrigger = page.locator(surface === 'hub' ? '#hub-collab-name' : '#collab-name')
  const profile = page.locator(surface === 'hub' ? '#hub-name-dialog' : '#name-dialog')
  await profileTrigger.click()
  const profileTitle = await profile.locator('h2').innerText()
  await expect(page.getByRole('dialog', { name: profileTitle, exact: true })).toBeVisible()
  await expect(profile.getByRole('textbox', { name: profileTitle, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(profileTrigger).toBeFocused()
  const themeTrigger = page.locator('.theme-trigger')
  await themeTrigger.click()
  const appearance = page.locator('.theme-dialog')
  const appearanceTitle = await appearance.locator('h2').innerText()
  await expect(page.getByRole('dialog', { name: appearanceTitle, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(themeTrigger).toBeFocused()
  if (surface === 'workspace') {
    const createFile = page.locator('#new-file')
    await createFile.click()
    const title = await page.locator('#action-dialog-title').innerText()
    const dialog = page.getByRole('dialog', { name: title, exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('textbox', { name: title, exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(createFile).toBeFocused()
  }
})

test('Rebuttal form dialogs expose the visible operation as their accessible name', async ({ page }) => {
  await page.route('**/api/rebuttal/projects/**/state', route => route.fulfill({ json: { revision: 0, enabled: true, rounds: [], jobs: [] } }))
  await page.goto('/p/review-dialog-contract/rebuttal?lang=en')
  const iframe = page.locator('iframe.paper-review-frame')
  await expect(iframe).toHaveClass(/is-active/)
  await expect(iframe).toHaveAttribute('aria-hidden', 'false')
  const review = page.frameLocator('iframe.paper-review-frame')
  const createRound = review.getByRole('button', { name: 'Create your first round', exact: true })
  await createRound.click()
  const title = await review.locator('#dialog-title').innerText()
  expect(title).toBe('Create rebuttal round')
  const dialog = review.getByRole('dialog', { name: title, exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('textbox', { name: 'Round title', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(createRound).toBeFocused()
})

for (const theme of ['light','dark']) test(`overflowing assistant tabs expose a scroll affordance in ${theme}`,async({page})=>{
  await page.setViewportSize({width:1600,height:1000})
  await page.addInitScript(theme=>localStorage.setItem('paper-workspace-theme',theme),theme)
  let requests=0
  await page.route('**/api/codex',route=>{requests++;return route.abort()})
  await page.goto(`/p/tab-discovery-${theme}-${Date.now()}?lang=en`)
  await page.waitForFunction(()=>workspaceReadyForCompile)
  const tabs=page.locator('.assistant-tabs'),task=page.getByRole('tab',{name:'Tasks',exact:true})
  await expect(tabs).toHaveCSS('scrollbar-width','thin')
  await expect(page.locator('#assistant-tabs-next')).toBeVisible()
  await page.locator('#assistant-tabs-next').click()
  await expect.poll(()=>tabs.evaluate(node=>node.scrollLeft)).toBeGreaterThan(0)
  await task.click()
  await expect(task).toHaveAttribute('aria-selected','true')
  await expect(page.locator('#assistant-tabs-prev')).toBeVisible()
  await expect(page.getByRole('tabpanel',{name:'Tasks',exact:true})).toBeVisible()
  expect(requests).toBe(0)
})
