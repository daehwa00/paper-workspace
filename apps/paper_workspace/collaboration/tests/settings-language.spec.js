import { test, expect } from './fixtures.js'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
const artifacts = resolve(import.meta.dirname, '../../../../.omx/artifacts/linear-refresh/remaining-settings')
mkdirSync(artifacts, { recursive: true })

async function expectContained(dialog) {
  expect(await dialog.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
  const parent = await dialog.boundingBox()
  for (const element of await dialog.locator('input:not([type=radio]), .color-option, .property-trigger, .dialog-actions button').all()) {
    if (!await element.isVisible()) continue
    const box = await element.boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(parent.x)
    expect(box.x + box.width).toBeLessThanOrEqual(parent.x + parent.width + 1)
  }
}

for (const surface of ['hub', 'workspace']) for (const theme of ['light', 'dark']) for (const lang of ['ko', 'en']) {
  test(`${surface} settings rows preserve keyboard, storage and responsive behavior ${theme} ${lang}`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.addInitScript(theme => localStorage.setItem('paper-workspace-theme', theme), theme)
    await page.route('**/_auth/verify', route => route.fulfill({ status: 200, json: {} }))
    await page.goto(surface === 'hub' ? `/hub.html?lang=${lang}` : `/p/settings-${theme}-${lang}-${Date.now()}?lang=${lang}`)
    const profileTrigger = page.locator(surface === 'hub' ? '#hub-collab-name' : '#collab-name')
    const profile = page.locator('.name-dialog'), name = profile.locator('input:not([type=radio])')
    const metrics = []
    for (const width of [320, 390, 1024, 1600]) {
      await page.setViewportSize({ width, height: 1000 })
      await profileTrigger.click()
      await expect(profile).toBeVisible()
      await name.fill(lang === 'ko' ? '이름이 긴 공동 연구자와 논문 공동 저자' : 'An exceptionally long researcher')
      await expectContained(profile)
      expect((await profile.locator("legend").boundingBox()).width).toBe(1)
      const selected = profile.locator('input[type=radio]:checked')
      await page.keyboard.press('Tab')
      await selected.focus()
      await expect(selected.locator('+ .color-swatch')).toHaveCSS('outline-style', 'solid')
      await profile.screenshot({ path: resolve(artifacts, `${surface}-profile-${theme}-${lang}-${width}.png`) })
      await page.keyboard.press('Escape')
      await expect(profileTrigger).toBeFocused()
      expect(await page.evaluate(() => localStorage.getItem('collab-name'))).toBe('Test Author')
      const themeTrigger = page.locator('.theme-trigger')
      if (!await themeTrigger.isVisible()) await page.locator('#mobile-utilities > summary').click()
      await themeTrigger.click()
      const appearance = page.locator('.theme-dialog')
      await expect(appearance.locator('.eyebrow')).toHaveCount(0)
      await appearance.locator('.settings-copy small').evaluateAll((elements, lang) => {
        elements.forEach(el => el.textContent = lang === 'ko' ? '이 브라우저의 모든 논문 작업 화면에 함께 적용되는 화면 설정입니다.' : 'These appearance preferences apply to every paper workspace in this browser.')
      }, lang)
      await expectContained(appearance)
      expect((await appearance.locator(".dialog-actions button").boundingBox()).height).toBe(width < 768 ? 44 : 28)
      await expect(appearance.locator('.settings-row')).toHaveCount(1)
      await expect(appearance.locator('input[name="workspace-theme"]')).toHaveCount(0)
      const select = appearance.locator('select[name="workspace-theme"]')
      const picker = appearance.locator('.property-trigger')
      const menu = appearance.locator('.property-menu')
      const labels = lang === 'ko' ? { system:'시스템', light:'라이트', dark:'다크' } : { system:'System', light:'Light', dark:'Dark' }
      await expect(select).toHaveValue(theme)
      const copyBox = await appearance.locator('.settings-copy').boundingBox(), controlBox = await picker.boundingBox()
      expect(controlBox.x).toBeGreaterThanOrEqual(copyBox.x + copyBox.width)
      expect(Math.abs(controlBox.y + controlBox.height / 2 - copyBox.y - copyBox.height / 2)).toBeLessThanOrEqual(1)
      const original = await select.inputValue()
      await picker.click()
      await expect(menu).toBeVisible()
      await expect(menu.getByRole('option', { name:labels[original], exact:true })).toHaveAttribute('aria-selected', 'true')
      const alternative = theme === 'dark' ? 'light' : 'dark'
      await menu.getByRole('option', { name:labels[alternative], exact:true }).click()
      await expect(select).toHaveValue(alternative)
      await expect(picker).toBeFocused()
      expect(await page.evaluate(() => localStorage.getItem('paper-workspace-theme'))).toBe(alternative)
      expect(await select.evaluate(el => new FormData(el.form).get('workspace-theme'))).toBe(alternative)
      await picker.press('Enter')
      await page.keyboard.press('ArrowDown')
      await page.keyboard.press('Enter')
      await expect(select).toHaveValue('system')
      expect(await page.evaluate(() => localStorage.getItem('paper-workspace-theme'))).toBe('system')
      await picker.press('Enter')
      await page.keyboard.press('ArrowDown')
      await page.keyboard.press('ArrowDown')
      await page.keyboard.press('Escape')
      await expect(menu).toBeHidden()
      await expect(appearance).toBeVisible()
      await expect(picker).toBeFocused()
      await expect(select).toHaveValue('system')
      await select.selectOption(theme)
      await expect(picker).toContainText(labels[theme])
      await expect(themeTrigger).toHaveAttribute('title', await themeTrigger.getAttribute('aria-label'))
      await picker.click()
      await expect(menu.getByRole('option', { name:labels[theme], exact:true })).toHaveAttribute('aria-selected', 'true')
      await menu.screenshot({ path: resolve(artifacts, `${surface}-appearance-menu-${theme}-${lang}-${width}.png`) })
      await page.keyboard.press('Escape')
      await page.evaluate(() => document.fonts.ready)
      await page.mouse.move(0, 0)
      metrics.push(await appearance.evaluate(el => {
        const row = el.querySelector('.settings-row'), group = el.querySelector('.settings-group')
        const styles = node => { const s = getComputedStyle(node); return { color:s.color, background:s.backgroundColor, border:s.borderColor, radius:s.borderRadius, font:s.fontSize, weight:s.fontWeight, lineHeight:s.lineHeight } }
        return { width:innerWidth, dialog:styles(el), group:styles(group), row:styles(row), label:styles(row.querySelector('strong')), description:styles(row.querySelector('small')), control:styles(row.querySelector('.property-trigger')),nativeValue:row.querySelector('select').value,formValue:new FormData(row.querySelector('select').form).get('workspace-theme'),rowCount:el.querySelectorAll('.settings-row').length, rowHeight:row.getBoundingClientRect().height, groupOverflow:group.scrollWidth-group.clientWidth }
      }))
      await appearance.screenshot({ path: resolve(artifacts, `${surface}-appearance-${theme}-${lang}-${width}.png`) })
      if (width === 320) await appearance.locator('.dialog-actions button').click()
      else await page.keyboard.press('Escape')
      await expect(appearance).toBeHidden()
      if (width >= 768) await expect(themeTrigger).toBeFocused()
    }
    await page.setViewportSize({ width:1600, height:1000 })
    await profileTrigger.click()
    await name.fill('Saved Researcher')
    await profile.locator('.color-option').last().click()
    await profile.locator('.dialog-actions .primary').click()
    await expect(profile).toBeHidden()
    await expect.poll(() => page.evaluate(() => localStorage.getItem('collab-name'))).toBe('Saved Researcher')
    await expect.poll(() => page.evaluate(() => localStorage.getItem('collab-color'))).toBe('#db2777')
    await page.reload()
    expect(await page.evaluate(() => localStorage.getItem('paper-workspace-theme'))).toBe(theme)
    await profileTrigger.click()
    await expect(name).toHaveValue('Saved Researcher')
    await expect(profile.locator('input[value="#db2777"]')).toBeChecked()
    await page.keyboard.press('Escape')
    await page.locator('.theme-trigger').click()
    await expect(page.locator('.theme-dialog select[name=workspace-theme]')).toHaveValue(theme)
    await page.keyboard.press('Escape')
    writeFileSync(resolve(artifacts, `${surface}-${theme}-${lang}-metrics.json`), JSON.stringify(metrics, null, 2))
  })
}
