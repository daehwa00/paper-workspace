import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { test, expect } from './fixtures.js'

const output = resolve(import.meta.dirname, '../../../../.omx/artifacts/linear-refresh/remaining-controls')
mkdirSync(output, { recursive: true })

// Exercise the real toolbar, native radio group and API-rendered backup rows.
// No proposal or analysis action is submitted by this presentation regression.
test('remaining workspace controls share dimensions, states and keyboard focus', async ({ browser }) => {
  test.setTimeout(120_000)
  const metrics = []
  for (const theme of ['light', 'dark']) for (const width of [320, 390, 1024, 1600]) for (const language of ['ko', 'en']) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' })
    await context.addInitScript(theme => {
      localStorage.setItem('collab-name', 'Control Review')
      localStorage.setItem('collab-name-user-set', '1')
      localStorage.setItem('paper-workspace-theme', theme)
    }, theme)
    const page = await context.newPage()
    const errors = [], llm = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (/\/api\/(codex|rebuttal\/.*analysis)/.test(request.url())) llm.push(request.url()) })
    await page.route('**/api/backups/projects/*/snapshots', route => route.fulfill({ json: { snapshots: [{ id: 'control-review', title: language === 'ko' ? '학회 제출 전 검토 및 공동저자 확인을 위한 아주 긴 논문 원고 백업 이름' : 'A long manuscript backup name for final submission and coauthor review', reason: 'manual', created_at: '2026-10-27T00:00:00Z' }] } }))
    await page.goto(`/p/remaining-${theme}-${width}-${language}-${Date.now()}?lang=${language}`)
    await page.waitForFunction(() => workspaceReadyForCompile)
    await page.evaluate(() => document.fonts.ready)
    const controlHeight = width < 768 ? 44 : 28
    const chrome = await page.evaluate(() => {
      const s = getComputedStyle(document.documentElement)
      return Object.fromEntries(['--theme-accent', '--theme-hover', '--theme-selected', '--theme-control', '--theme-control-border', '--theme-control-text', '--theme-text'].map(key => [key, s.getPropertyValue(key).trim()]))
    })
    const rgb = hex => `rgb(${hex.slice(1).match(/../g).map(n => parseInt(n, 16)).join(', ')})`
    const editor = page.locator('#editor-view .cm-content')
    await editor.click()
    await page.keyboard.press('Control+f')
    const search = page.locator('.paper-search-panel')
    await expect(search).toBeVisible()
    const boxes = await search.locator('.paper-search-field,.paper-search-button,.paper-search-option').evaluateAll(elements => elements.map(e => ({ class: e.className, height: e.getBoundingClientRect().height })))
    for (const box of boxes) expect(box.height, `${theme}/${width}/${language}: ${box.class}`).toBe(controlHeight)
    await expect(search.locator('svg').first()).toHaveCSS('stroke-width', '1.5px')
    const option = search.locator('.paper-search-option').first()
    await option.locator('input').focus()
    await expect(option).toHaveCSS('outline-color', rgb(chrome['--theme-accent']))
    await expect(option).toHaveCSS('outline-width', '2px')
    await page.keyboard.press('Space')
    await expect(option.locator('input')).toBeChecked()
    await search.locator('[name=search]').fill(language === 'ko' ? '분석을 실행하지 않고 매우 긴 검색 문구를 입력해도 작업 영역을 유지합니다' : 'A long query preserves the manuscript editor without starting analysis')
    await page.screenshot({ path: resolve(output, `search-${theme}-${width}-${language}.png`), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(search).toBeHidden()
    if (width < 768) await page.locator('#focus-modes [data-focus=assistant]').click()
    else if (width <= 1180) await page.locator('#toggle-assistant').click()
    await page.locator('#tab-assist').click()
    await page.locator('#model-settings summary').click()
    const model = page.locator('.model-option').nth(1)
    await model.locator('.model-option-copy span').evaluate((e, language) => { e.textContent = language === 'ko' ? '문단의 의미와 논리 구조를 유지하면서 공동저자와 검토할 수 있도록 자연스럽고 일관되게 다듬습니다.' : 'Edit the paragraph with consistent language while preserving its meaning and structure for coauthor review.' }, language)
    await model.hover()
    await expect(model).toHaveCSS('background-color', rgb(chrome['--theme-hover']))
    await page.mouse.down()
    await expect(model).toHaveCSS('background-color', rgb(chrome['--theme-selected']))
    await page.mouse.up()
    await expect(model.locator('input')).toBeChecked()
    await expect(model).toHaveCSS('background-color', rgb(chrome['--theme-selected']))
    await expect(model.locator('.model-option-copy span')).toHaveCSS('color', rgb(chrome['--theme-text']))
    await model.locator('input').focus()
    await page.keyboard.press('Tab')
    await page.keyboard.press('Shift+Tab')
    await expect(model).toHaveCSS('outline-width', '2px')
    await page.screenshot({ path: resolve(output, `model-${theme}-${width}-${language}.png`), animations: 'disabled' })
    await page.locator('#tab-sources').click()
    const backup = page.locator('#create-backup')
    await expect(backup).toHaveCSS('background-color', rgb(chrome['--theme-control']))
    await expect(backup).toHaveCSS('color', rgb(chrome['--theme-control-text']))
    await expect(page.locator('#checkpoint-name')).toHaveCSS('height', `${controlHeight}px`)
    await page.locator('#checkpoint-name').fill(language === 'ko' ? '공동저자 검토 후 제출할 원고의 긴 버전 이름' : 'A long submission version name after coauthor review')
    const group = page.locator('.backup-card>.tool-row').first()
    await expect(group).toHaveCSS('border-top-width', '0px')
    for (const action of await group.locator('button').all()) {
      expect((await action.boundingBox()).height).toBe(controlHeight)
      await action.focus()
      await page.keyboard.press('Tab')
      await page.keyboard.press('Shift+Tab')
      await expect(action).toHaveCSS('outline-width', '2px')
    }
    await backup.evaluate(e => { e.disabled = true; e.setAttribute('aria-busy', 'true') })
    await expect(backup).toHaveCSS('opacity', '0.5')
    expect(await backup.evaluate(e => getComputedStyle(e, '::before').content)).toBe('""')
    await page.screenshot({ path: resolve(output, `backup-${theme}-${width}-${language}.png`), animations: 'disabled' })
    await page.locator('#tab-tasks').click()
    await expect(page.locator('#task-title')).toHaveCSS('height', `${controlHeight}px`)
    await page.locator('#task-title').fill(language === 'ko' ? '실험 결과와 답변 초안을 공동저자에게 검토받기 위한 긴 작업 이름' : 'Ask coauthors to review experimental findings and the draft response before submission')
    await page.screenshot({ path: resolve(output, `tasks-${theme}-${width}-${language}.png`), animations: 'disabled' })
    const overflow = await page.evaluate(() => Math.max(0, document.documentElement.scrollWidth - innerWidth))
    expect(overflow).toBe(0)
    expect(errors).toEqual([])
    expect(llm).toEqual([])
    metrics.push({ theme, width, language, controlHeight, search: boxes, overflow, errors, llmRequests: llm.length })
    await context.close()
  }
  writeFileSync(resolve(output, 'metrics.json'), JSON.stringify(metrics, null, 2))
})
