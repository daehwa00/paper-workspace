import {test,expect} from './fixtures.js'

const catalog={projects:[{slug:'alpha',display_name:'Alpha manuscript'},{slug:'beta',display_name:'Beta research'}]}

test('comment activity localizes actions and resolves by keyboard without row navigation',async({page})=>{
  await page.setViewportSize({width:1600,height:1000})
  await page.goto(`/p/activity-${Date.now()}?lang=en`)
  await page.waitForFunction(()=>workspaceReadyForCompile&&sharedMetadataReady)
  await page.evaluate(()=>{
    const text=editorValue().slice(0,32)
    addCommentForSelection({file:state.current,start:0,end:text.length,text},'Check this claim before submission.')
  })
  await page.locator('#tab-comments').click()
  const resolve=page.getByRole('button',{name:'Resolve',exact:true})
  await expect(resolve).toBeVisible()
  await resolve.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('#comment-list .comment-card')).toHaveCount(0)
  await expect(page.locator('#comments')).toBeVisible()
})

test('workspace brand returns directly to the project hub',async({page})=>{
  await page.route('**/projects/index.json',route=>route.fulfill({json:catalog}))
  await page.goto('/p/alpha?lang=en')
  await page.waitForFunction(()=>workspaceReadyForCompile)
  const link=page.locator('.project-frame-brand')
  await expect(link).toHaveAttribute('href','/')
  await expect(link).not.toHaveAttribute('role','button')
  await link.click()
  await expect(page).toHaveURL(/\/$/)
})

test('searchable property menu updates the real project sort and restores trigger focus',async({page})=>{
  await page.route('**/projects/index.json',route=>route.fulfill({json:{projects:[{slug:'z',display_name:'Zulu'},{slug:'a',display_name:'Alpha'}]}}))
  await page.route('**/api/backups/activity',route=>route.fulfill({json:{projects:[{project_id:'z',modified_at:'2026-10-27T00:00:00Z'},{project_id:'a',modified_at:'2026-10-26T00:00:00Z'}]}}))
  await page.goto('/hub.html?lang=en')
  await expect(page.locator('.project-card').first()).toContainText('Zulu')
  const trigger=page.locator('#project-sort').locator('..').getByRole('button')
  await trigger.click()
  const picker=page.locator('.property-menu:visible')
  await picker.getByRole('searchbox').fill('Name')
  await picker.getByRole('option',{name:'Name',exact:true}).click()
  await expect(page.locator('#project-sort')).toHaveValue('name')
  await expect(page.locator('.project-card').first()).toContainText('Alpha')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await picker.getByRole('searchbox').fill('no matching property')
  await expect(picker).toContainText('No matching options')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

for(const width of [320,390,1024,1600])test(`agent composer and contextual file actions at ${width}`,async({page})=>{
  const requests=[]
  page.on('request',r=>{if(r.url().includes('/api/codex'))requests.push(r.url())})
  await page.setViewportSize({width,height:900})
  await page.goto('/?lang=en')
  await page.waitForFunction(()=>workspaceReadyForCompile)
  if(width<768)await page.locator('[data-focus=assistant]').click()
  else if(width===1024)await page.locator('#toggle-assistant').click()
  await expect(page.locator('#assist .assistant-intro')).toBeVisible()
  const [panel,form]=await Promise.all([page.locator('#assistant-panel').boundingBox(),page.locator('#codex-request-form').boundingBox()])
  expect(form.y).toBeGreaterThan(panel.y+panel.height/2)
  expect(form.y+form.height).toBeLessThanOrEqual(panel.y+panel.height)
  await expect(page.locator('#composer-file')).toHaveText('main.tex')
  await page.locator('#model-settings summary').click()
  await expect(page.locator('.model-options')).toBeVisible()
  const menu=await page.locator('.model-options').boundingBox()
  expect(menu.y).toBeGreaterThanOrEqual(panel.y)
  expect(menu.y+menu.height).toBeLessThanOrEqual(form.y+10)
  await page.locator('#model-settings summary').click()
  if(width<768)await page.locator('[data-focus=source]').click()
  else if(width===1024)await page.locator('#close-assistant').click()
  await page.locator('#active-file-actions').click()
  await expect(page.locator('#tree-menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#active-file-actions')).toBeFocused()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(width)
  expect(requests).toEqual([])
})
