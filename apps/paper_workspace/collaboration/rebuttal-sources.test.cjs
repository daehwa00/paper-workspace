'use strict'

const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const test = require('node:test')
const Y = require('yjs')
const { createRebuttalSourceSync } = require('./rebuttal-sources.cjs')

const fixture = t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'rebuttal-sources-'))
  const document = new Y.Doc()
  const responses = document.getMap('rebuttalResponses')
  const source = key => path.join(root, 'rebuttal', 'responses', `${key}.md`)
  const status = key => document.getMap('rebuttalSourceStatus').get(key)
  const syncs = []
  const start = (doc = document, options = {}) => {
    const sync = createRebuttalSourceSync({ document: doc, projectRoot: root, pollMs: 0, ...options })
    syncs.push(sync)
    return sync
  }
  t.after(() => {
    syncs.forEach(sync => sync.close())
    document.destroy()
    fs.rmSync(root, { recursive: true, force: true })
  })
  return { root, document, responses, source, status, start }
}
const replace = (document, text, value) => document.transact(() => {
  text.delete(0, text.length)
  text.insert(0, value)
})

test('web edits write Markdown; server edits update shared text without touching paper files', t => {
  const f = fixture(t)
  const paper = new Y.Text('paper stays')
  f.document.getMap('files').set('paper/main.tex', paper)
  f.responses.set('draft:R1', new Y.Text('initial\nsecond\n'))
  const sync = f.start()
  assert.equal(fs.readFileSync(f.source('draft:R1'), 'utf8'), 'initial\nsecond\n')
  f.responses.get('draft:R1').insert(0, 'web ')
  assert.equal(fs.readFileSync(f.source('draft:R1'), 'utf8'), 'web initial\nsecond\n')
  fs.writeFileSync(f.source('draft:R1'), 'web initial\nserver second\n')
  sync.sync()
  assert.equal(f.responses.get('draft:R1').toString(), 'web initial\nserver second\n')
  assert.equal(paper.toString(), 'paper stays')
  assert.equal(f.status('draft:R1').state, 'synced')
})

