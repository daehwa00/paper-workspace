test('overlapping changes durably preserve both copies and retain conflict status', t => {
  const f = fixture(t)
  f.responses.set('R1', new Y.Text('original\n'))
  const sync = f.start()
  fs.writeFileSync(f.source('R1'), 'server\n')
  replace(f.document, f.responses.get('R1'), 'web\n')
  assert.equal(f.responses.get('R1').toString(), 'server\n')
  const conflict = f.status('R1')
  assert.equal(conflict.state, 'conflict')
  assert.deepEqual(conflict.conflictPaths.map(p => fs.readFileSync(path.join(f.root, p), 'utf8')), ['web\n', 'server\n'])
  sync.sync()
  assert.deepEqual(f.status('R1'), conflict)
})

