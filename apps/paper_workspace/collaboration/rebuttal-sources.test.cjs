test('symlink, traversal, malformed text and size limits never replace shared text or outside files', t => {
  const f = fixture(t)
  const sync = f.start(f.document, { maxBytes: 32 })
  const outside = path.join(f.root, 'outside.md')
  fs.writeFileSync(outside, 'outside')
  fs.mkdirSync(path.dirname(f.source('R1')), { recursive: true })
  fs.symlinkSync(outside, f.source('R1'))
  assert.throws(() => sync.ensureTexts([{ key: 'R1', initial: '' }]))
  assert.throws(() => sync.ensureTexts([{ key: '../escape', initial: '' }]))
  assert.equal(f.responses.has('R1'), false)
  f.responses.set('R1', new Y.Text('keep web'))
  assert.equal(f.status('R1').state, 'error')
  assert.equal(f.responses.get('R1').toString(), 'keep web')
  assert.equal(fs.readFileSync(outside, 'utf8'), 'outside')
  fs.unlinkSync(f.source('R1'))
  fs.writeFileSync(f.source('R1'), Buffer.from([0xff]))
  sync.sync()
  assert.equal(f.status('R1').state, 'error')
  fs.writeFileSync(f.source('R1'), 'x'.repeat(33))
  sync.sync()
  assert.equal(f.status('R1').state, 'error')
  assert.equal(f.responses.get('R1').toString(), 'keep web')
  fs.writeFileSync(f.source('R1'), 'recovered')
  sync.sync()
  assert.equal(f.responses.get('R1').toString(), 'recovered')
})

