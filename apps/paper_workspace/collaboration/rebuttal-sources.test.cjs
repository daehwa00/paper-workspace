test('offline Yjs edits merged after server changes preserve the two conflicting versions', t => {
  const f = fixture(t)
  f.responses.set('R1', new Y.Text('original\n'))
  const sync = f.start()
  const offline = new Y.Doc()
  Y.applyUpdate(offline, Y.encodeStateAsUpdate(f.document))
  replace(offline, offline.getMap('rebuttalResponses').get('R1'), 'offline web\n')
  fs.writeFileSync(f.source('R1'), 'server replacement\n')
  // The offline edit arrives before the next filesystem poll.
  Y.applyUpdate(f.document, Y.encodeStateAsUpdate(offline))
  assert.equal(f.responses.get('R1').toString(), 'server replacement\n')
  const status = f.status('R1')
  assert.equal(status.state, 'conflict')
  assert.deepEqual(status.conflictPaths.map(p => fs.readFileSync(path.join(f.root, p), 'utf8')), ['offline web\n', 'server replacement\n'])
  sync.sync()
  assert.equal(f.status('R1').state, 'conflict')
})

