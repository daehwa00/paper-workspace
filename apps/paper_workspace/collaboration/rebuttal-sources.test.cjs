test('a save to the displaced response inode is preserved as a conflict', t => {
  const f = fixture(t)
  const text = new Y.Text('baseline')
  f.responses.set('R1', text)
  const sync = f.start()
  const originalRename = fs.renameSync
  fs.renameSync = (from, to) => {
    if (to === f.source('R1')) fs.writeFileSync(to, 'external edit at rename')
    return originalRename(from, to)
  }
  try {
    text.insert(text.length, ' plus web')
  } finally {
    fs.renameSync = originalRename
  }
  const status = f.status('R1')
  assert.equal(status.state, 'conflict')
  assert.equal(text.toString(), 'baseline plus web')
  assert.equal(fs.readFileSync(path.join(f.root, status.conflictPaths[0]), 'utf8'), 'external edit at rename')
  sync.sync()
  assert.deepEqual(f.status('R1'), status)
})
