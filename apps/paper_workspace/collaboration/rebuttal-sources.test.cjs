test('history respects version and serialized byte bounds while retaining recovery outside the merge window', t => {
  const f = fixture(t)
  f.responses.set('R1', new Y.Text('first\nsecond\nthird\n'))
  const sync = f.start(f.document, { maxBytes: 1280 })
  for (let index = 1; index <= 6; index += 1) replace(f.document, f.responses.get('R1'), `${index}`.repeat(500))
  const baseline = JSON.parse(fs.readFileSync(path.join(f.root, 'rebuttal/.sync/R1.json'), 'utf8'))
  assert.ok(baseline.history.length <= 4)
  assert.ok(baseline.history.reduce((sum, value) => sum + Buffer.byteLength(JSON.stringify(value)), 0) <= 1280)
  const latestWeb = f.responses.get('R1').toString()
  fs.writeFileSync(f.source('R1'), 'first\nsecond\nserver third\n')
  sync.sync()
  const status = f.status('R1')
  const recovery = status.state === 'conflict' ? status.conflictPaths[0] : status.recoveryPath
  assert.equal(fs.readFileSync(path.join(f.root, recovery), 'utf8'), latestWeb)
})

